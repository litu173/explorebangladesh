"""Validate the road network against the district map and write assets/js/roads.js."""
import json,re,math,sys
sys.path.insert(0,'tools'); from roads_src import J,E
exec(open('tools/roads_fit.py').read().split("HQ=json.load")[0])   # polys, inside(), which()
HQ=json.load(open('tools/hq.json')); P=json.load(open('tools/proj.json'))
kx=(P['maxx']-P['minx'])/(P['e']-P['w']); ky=(P['maxy']-P['miny'])/(P['n']-P['s'])
proj=lambda la,lo:(P['minx']+(lo-P['w'])*kx, P['miny']+(P['n']-la)*ky)
N={k:(v[0],v[1],k) for k,v in HQ.items()}; N.update({k:v for k,v in J.items()})
problems=[]
for k,(la,lo,d) in N.items():
    w=which(*proj(la,lo))
    if w!=d: problems.append(f'node {k} expected {d} got {w}')
for e in E:
    a,b=e[0],e[1]
    if a not in N or b not in N: problems.append(f'unknown node in {e}'); continue
    if len(e)>2: continue
    (x1,y1),(x2,y2)=proj(*N[a][:2]),proj(*N[b][:2])
    out=sum(1 for t in [i/24 for i in range(1,24)] if which(x1+(x2-x1)*t,y1+(y2-y1)*t) is None)
    if out>1: problems.append(f'edge {a}-{b} leaves land at {out}/23 samples')
# connectivity
adj={k:set() for k in N}
for e in E: adj[e[0]].add(e[1]); adj[e[1]].add(e[0])
seen={'dhaka'}; st=['dhaka']
while st:
    for n in adj[st.pop()]:
        if n not in seen: seen.add(n); st.append(n)
problems+= [f'unreachable {k}' for k in N if k not in seen]
print('nodes',len(N),'edges',len(E)); print('\n'.join(problems) or 'all good')
out={'proj':{k:round(v,4) for k,v in P.items() if k!='mode'},'nodes':{k:[v[0],v[1],v[2]] for k,v in N.items()},'edges':[list(e) for e in E]}
open('assets/js/roads.js','w',encoding='utf8').write('/* Road network (district HQs + highway junctions) for drawing trip routes. Generated by tools/build_roads.py */\nwindow.EB_ROADS='+json.dumps(out,separators=(',',':'))+';\n')
# guide id -> [lat, lon] from the live site, used for route end points
import glob
C={}
for f in glob.glob('assets/data/guide/*.json'):
    for k,v in json.load(open(f,encoding='utf8')).items():
        if v.get('ll') and len(v['ll'])==2: C[k]=[round(float(v['ll'][0]),4),round(float(v['ll'][1]),4)]
open('assets/js/roads.js','a',encoding='utf8').write('/* guide id -> [lat, lon] from the live site, used for route end points */\nwindow.EB_COORDS='+json.dumps(C,separators=(',',':'))+';\n')
